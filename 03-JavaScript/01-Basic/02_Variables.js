// 1. Variable Declaration
let age;
console.log(age);


// 2. Variable Initialization
age = 20;
console.log(age);


// 3. Declaration + Initialization
let marks = 90;
console.log(marks);


// 4. Using a Variable
let name = "Ashwani";
console.log(name);


// 5. Using Variables in an Expression
let a = 10;
let b = 20;
console.log(a + b);


// 6. Using let
let studentAge = 20;
studentAge = 21;
console.log(studentAge);


// 7. Reassigning a Variable
let score = 80;
score = 95;
console.log(score);


// 8. Using const
const pi = 3.14;
console.log(pi);


// 9. Using var
var number = 100;
console.log(number);


// 10. Reassigning var
var value = 10;
value = 20;
console.log(value);


// 11. Redeclaring var
var x = 10;
var x = 20;
console.log(x);


// 12. Changing a Variable Multiple Times
let points = 50;
points = 75;
points = 100;
console.log(points);


// 13. Copying a Variable
let firstNumber = 10;
let secondNumber = firstNumber;

secondNumber = 20;

console.log(firstNumber);
console.log(secondNumber);


// 14. Different Types of Values
let studentName = "Ashwani";
let studentMarks = 90;
let isStudent = true;

console.log(studentName);
console.log(studentMarks);
console.log(isStudent);


// 15. Camel Case Naming
let firstName = "Ashwani";
let lastName = "Chauhan";
let totalMarks = 500;

console.log(firstName);
console.log(lastName);
console.log(totalMarks);


// 16. Constants
const birthYear = 2005;
const country = "India";

console.log(birthYear);
console.log(country);


// 17. Multiple Variables
let city = "Delhi";
let ageOfStudent = 20;
let percentage = 85.5;

console.log(city);
console.log(ageOfStudent);
console.log(percentage);


// 18. Block Scope
{
    let blockAge = 20;
    console.log(blockAge);
}


// 19. Const Object
const student = {
    name: "Ashwani"
};

student.name = "Rahul";

console.log(student.name);